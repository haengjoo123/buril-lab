import type { WasteBatchDraft } from '../src/types';
import type { GoldenConcentrationScenario, WasteGoldenSetV2Row } from '../src/features/wasteGoldenSet/schema';
import { buildWasteHandlingComponents } from '../src/services/wasteLogService';
import { analyzeWasteBatch } from '../src/utils/wasteBatch';
import { batchForGoldenRow } from './wasteGoldenSetV2';

/** The decision fields record_waste_handling_v2 re-derives and compares. */
export interface ServerParityExpectation {
    decisionStatus: string;
    streamCode: string;
    hazardFlags: string[];
    routingBasis: string;
}

export interface ServerParityCase {
    id: string;
    matrix: string;
    components: unknown[];
    confirmation: Record<string, unknown>;
    expected: ServerParityExpectation;
}

const CAPTURED_AT = '2026-08-08T00:00:00.000Z';

const parityCase = (id: string, draft: WasteBatchDraft): ServerParityCase => {
    // Component timestamps are not decision evidence; pin them so the
    // generated fixture is reproducible.
    const batch = {
        ...draft,
        components: draft.components.map((component) => ({ ...component, capturedAt: CAPTURED_AT })),
    };
    const decision = analyzeWasteBatch(batch);
    return {
        id,
        matrix: batch.matrix,
        components: buildWasteHandlingComponents(batch.components),
        // The analysis-relevant part of buildWasteHandlingRpcPayload's confirmationSnapshot.
        confirmation: {
            matrixSource: batch.matrixSource,
            incidentContext: batch.incidentContext,
            measuredBatchPh: batch.measuredPhStatus === 'measured' ? batch.measuredBatchPh ?? batch.measuredPh ?? null : null,
            measuredPhStatus: batch.measuredPhStatus,
            mixingState: batch.mixingState,
            ...(batch.mixingState === 'unknown' ? {} : { alreadyMixed: batch.mixingState === 'already_mixed' }),
            ...(batch.additionalComponentsStatus ? { additionalComponentsStatus: batch.additionalComponentsStatus } : {}),
            ...(batch.fluorideContainerStatus ? { fluorideContainerStatus: batch.fluorideContainerStatus } : {}),
        },
        expected: {
            decisionStatus: decision.decisionStatus,
            streamCode: decision.streamCode,
            hazardFlags: [...decision.hazardFlags].sort(),
            routingBasis: decision.routingBasis,
        },
    };
};

const sqlJson = (value: unknown): string => {
    const text = JSON.stringify(value);
    if (text.includes('$j$')) throw new Error('Parity case JSON cannot contain the $j$ quote tag.');
    return `$j$${text}$j$::jsonb`;
};

/**
 * pgTAP test that runs every case through private.analyze_waste_batch_v2 and
 * requires the exact fields record_waste_handling_v2 compares.
 */
export const renderServerParityPgTap = (cases: readonly ServerParityCase[]): string => [
    '-- GENERATED by scripts/waste-server-parity.test.ts; do not edit.',
    '-- Regenerate: WASTE_SERVER_PARITY_WRITE=1 npx vitest run scripts/waste-server-parity.test.ts',
    '--',
    '-- Every golden-set row and concentration scenario, serialized exactly as',
    '-- buildWasteHandlingComponents sends it, with the client analyzeWasteBatch',
    '-- answer. record_waste_handling_v2 rejects a write whose status, stream,',
    '-- hazard flags or routing basis differ from the server analysis.',
    'begin;',
    'create extension if not exists pgtap with schema extensions;',
    'set local search_path = public, extensions, pg_catalog;',
    'select plan(2);',
    '',
    'create temp table golden_parity_case(id text primary key, matrix text, components jsonb, confirmation jsonb, expected jsonb) on commit drop;',
    'insert into golden_parity_case values',
    cases.map((parityCase) => `  (${[
        `'${parityCase.id.replace(/'/g, "''")}'`,
        `'${parityCase.matrix}'`,
        sqlJson(parityCase.components),
        sqlJson(parityCase.confirmation),
        sqlJson(parityCase.expected),
    ].join(', ')})`).join(',\n') + ';',
    '',
    'create temp table golden_parity_result on commit drop as',
    'select c.id, c.expected, jsonb_build_object(',
    "    'decisionStatus', a->'decisionStatus', 'streamCode', a->'streamCode',",
    // The RPC compares flags as a set; sort bytewise like the JS fixture.
    "    'hazardFlags', (select coalesce(jsonb_agg(flag order by flag collate \"C\"), '[]'::jsonb)",
    "                    from jsonb_array_elements_text(a->'hazardFlags') as flags(flag)),",
    "    'routingBasis', a->'routingBasis'",
    ') as actual',
    'from golden_parity_case c',
    'cross join lateral private.analyze_waste_batch_v2(c.components, c.matrix, c.confirmation) a;',
    '',
    `select is((select count(*)::integer from golden_parity_result), ${cases.length}, 'every golden parity case was analyzed');`,
    'select is(',
    "  (select coalesce(jsonb_agg(jsonb_build_object('id', id, 'client', expected, 'server', actual) order by id), '[]'::jsonb)",
    '   from golden_parity_result where actual is distinct from expected),',
    "  '[]'::jsonb,",
    "  'the server analysis matches the client decision for every golden case'",
    ');',
    '',
    'select * from finish();',
    '',
    'rollback;',
    '',
].join('\n');

/** Every golden row and concentration scenario as a server-function input and the client's answer. */
export const buildServerParityCases = (
    rows: readonly WasteGoldenSetV2Row[],
    scenarios: readonly GoldenConcentrationScenario[] = [],
): ServerParityCase[] => {
    const byId = new Map(rows.map((row) => [row.id, row]));
    return [
        ...rows.map((row) => parityCase(row.id, batchForGoldenRow(row))),
        ...scenarios.map((scenario) => {
            const base = byId.get(scenario.baseRowId);
            if (!base) throw new Error(`Unknown concentration scenario base row: ${scenario.baseRowId}`);
            return parityCase(scenario.id, batchForGoldenRow(base, scenario));
        }),
    ];
};
