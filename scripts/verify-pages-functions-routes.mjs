import { readFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'

const EXPECTED = Object.freeze({
  version: 1,
  description: 'Generated by wrangler@4.125.0',
  include: Object.freeze(['/api/*']),
  exclude: Object.freeze([]),
})

export function verifyPagesFunctionsRoutes(value) {
  if (
    !value
    || typeof value !== 'object'
    || Array.isArray(value)
    || JSON.stringify(Object.keys(value).sort()) !== JSON.stringify(Object.keys(EXPECTED).sort())
    || value.version !== EXPECTED.version
    || value.description !== EXPECTED.description
    || JSON.stringify(value.include) !== JSON.stringify(EXPECTED.include)
    || JSON.stringify(value.exclude) !== JSON.stringify(EXPECTED.exclude)
  ) {
    throw new Error('Pages Functions routes must remain the exact Wrangler 4.125.0 /api/* contract.')
  }
  return true
}

export async function verifyPagesFunctionsRoutesFile(file) {
  let value
  try {
    value = JSON.parse(await readFile(file, 'utf8'))
  } catch {
    throw new Error('Pages Functions routes file is missing or invalid JSON.')
  }
  return verifyPagesFunctionsRoutes(value)
}

async function main() {
  if (process.argv.length !== 3) {
    throw new Error('Usage: node scripts/verify-pages-functions-routes.mjs <_routes.json>')
  }
  await verifyPagesFunctionsRoutesFile(process.argv[2])
  console.log('Verified exact Pages Functions /api/* route manifest.')
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : 'Pages Functions routes verification failed.')
    process.exitCode = 1
  })
}
