export type ContainerCopy = typeof KO;

export function containerCopy(language: string): ContainerCopy {
    return language.startsWith('ko') ? KO : EN;
}

export function containerStatusLabel(status: WasteContainerStatus, language: string): string {
    const copy = containerCopy(language);
    return status === 'active' ? copy.statusActive : status === 'sealed' ? copy.statusSealed : copy.statusCollected;
}

